const axios = require('axios');

const command = {
    name: "fluxai",
    alias: ["flux"],
    exec: async (sock, m, args) => {
        try {
            const prompt = args.join(" ");
            if (!prompt) {
                return sock.sendMessage(m.key.remoteJid, { text: "Please provide a prompt to generate an image.\n\n*Example:*\n.fluxai a beautiful sunset over mountains" }, { quoted: m });
            }

            const waitingMsg = await sock.sendMessage(m.key.remoteJid, { text: "🎨 Generating your image with FluxAI... This might take a moment." }, { quoted: m });

            const apiUrl = `https://api.siputzx.my.id/api/ai/flux?prompt=${encodeURIComponent(prompt)}`;
            
            // API se image ka data hasil karna
            const response = await axios.get(apiUrl, { responseType: "arraybuffer" });

            if (!response || !response.data) {
                return sock.sendMessage(m.key.remoteJid, { text: "Error: The API did not return a valid image. It might be down.", edit: waitingMsg.key }, { quoted: m });
            }

            const imageBuffer = Buffer.from(response.data, "binary");
            const caption = `*🎨 Image Generated by FluxAI*\n\n*✨ Prompt:* ${prompt}\n\n*Powered by MALIK-MD*`;

            await sock.sendMessage(m.key.remoteJid, {
                image: imageBuffer,
                caption: caption
            }, { quoted: m });

            // "Generating..." wala message delete kar dena
            await sock.sendMessage(m.key.remoteJid, { delete: waitingMsg.key });

        } catch (error) {
            console.error("FluxAI Error:", error);
            await sock.sendMessage(m.key.remoteJid, { text: `An error occurred. The API might be offline or the prompt was rejected.` }, { quoted: m });
        }
    }
};

module.exports = command;
